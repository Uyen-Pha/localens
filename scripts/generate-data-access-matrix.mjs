import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const thisFile = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(thisFile), "..");
const matrixPath = resolve(repoRoot, "docs/security/data-access-matrix.json");
const outputPath = resolve(repoRoot, "docs/security/data-access-matrix.md");

function loadMatrix(path = matrixPath) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function valueOrDefault(item, key, matrix) {
  return item[key] ?? matrix.defaults?.[key] ?? "";
}

function roleLabel(role, matrix) {
  const profile = matrix.roleProfiles?.[role];
  if (!profile) return role;
  return `${role} (login=${profile.rolcanlogin}, bypassrls=${profile.rolbypassrls}, ${profile.credential})`;
}

function escapeCell(value) {
  return String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
}

export function renderMatrixMarkdown(matrix = loadMatrix()) {
  const lines = [
    "# LocalLens data-access matrix",
    "",
    "> Generated from `docs/security/data-access-matrix.json`. Do not edit this file directly.",
    "> `service_role` is an Edge-only infrastructure credential and is never used as RLS evidence.",
    "",
    `API schemas: ${matrix.apiSchemas.join(", ")}  `,
    `Private schemas: ${matrix.privateSchemas.join(", ")}  `,
    `Migration owner for default privileges: ${matrix.migrationOwner}`,
    "",
    "## Roles",
    "",
    "| Role | Can login | Bypass RLS | Credential | Bypass justification |",
    "| --- | ---: | ---: | --- | --- |",
  ];

  for (const [name, profile] of Object.entries(matrix.roleProfiles).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`| ${escapeCell(name)} | ${profile.rolcanlogin} | ${profile.rolbypassrls} | ${escapeCell(profile.credential)} | ${escapeCell(profile.bypassJustification)} |`);
  }

  lines.push("", "## Tables", "", "| Object | Owner | API exposure | Readers | Writer operation | RLS | Force RLS | Policies | Grants | Credential |", "| --- | --- | --- | --- | --- | ---: | ---: | --- | --- | --- |");
  for (const item of [...matrix.tables].sort((a, b) => a.name.localeCompare(b.name))) {
    const readers = (item.readerRoles ?? matrix.defaults.readerRoles).map((role) => roleLabel(role, matrix)).join(", ");
    const policies = (item.policies ?? []).join(", ");
    const grants = (item.grants ?? matrix.defaults.grants).join(", ");
    lines.push(`| ${item.name} | ${valueOrDefault(item, "owner", matrix)} | ${valueOrDefault(item, "apiExposure", matrix)} | ${escapeCell(readers)} | ${escapeCell(valueOrDefault(item, "writerOperation", matrix))} | ${valueOrDefault(item, "rlsEnabled", matrix)} | ${valueOrDefault(item, "forceRls", matrix)} | ${escapeCell(policies)} | ${escapeCell(grants)} | ${valueOrDefault(item, "credential", matrix)} |`);
  }

  lines.push("", "## Views", "", "| Object | Owner | API exposure | Readers | security_invoker | security_barrier | Base-grant exception | Credential |", "| --- | --- | --- | --- | ---: | ---: | --- | --- |");
  for (const item of [...matrix.views].sort((a, b) => a.name.localeCompare(b.name))) {
    const readers = (item.readerRoles ?? []).map((role) => roleLabel(role, matrix)).join(", ");
    const exception = item.baseGrantException?.join("; ") ?? "none";
    lines.push(`| ${item.name} | ${valueOrDefault(item, "owner", matrix)} | ${valueOrDefault(item, "apiExposure", matrix)} | ${escapeCell(readers)} | ${item.securityInvoker ?? ""} | ${item.securityBarrier ?? ""} | ${escapeCell(exception)} | ${valueOrDefault(item, "credential", matrix)} |`);
  }

  lines.push("", "## Public RPCs", "", "| RPC | Owner | API reader/execute roles | Writer operation | Credential |", "| --- | --- | --- | --- | --- |");
  for (const item of [...matrix.rpcs].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`| ${item.name} | ${item.owner} | ${escapeCell(item.readerRoles.map((role) => roleLabel(role, matrix)).join(", "))} | ${escapeCell(item.writerOperation)} | ${item.credential} |`);
  }

  lines.push("", "## Internal functions", "", `Enumerated internal functions: ${matrix.internalFunctions.length}. All are non-API and must use a named NOLOGIN/NOBYPASSRLS owner, fixed empty search_path, and the final 5s statement timeout.`);
  lines.push("", matrix.internalFunctions.slice().sort().map((name) => `- \`${name}\``).join("\n"));

  lines.push("", "## Explicit grants", "", `Final explicit GRANT/REVOKE state is enumerated in [${matrix.grantManifest ?? "docs/security/grants-manifest.json"}] (${matrix.grantCount ?? "machine-readable"} records). The checker compares object, privilege, column list, and exact grantee bidirectionally after ordered migrations.`);

  lines.push("", "## Edge boundary checklist", "");
  for (const [key, value] of Object.entries(matrix.edgeBoundaryChecklist)) lines.push(`- **${key}**: ${value}`);
  lines.push("");
  return `${lines.join("\n")}\n`;
}

export function writeMatrixMarkdown({ matrix = loadMatrix(), output = outputPath } = {}) {
  const rendered = renderMatrixMarkdown(matrix);
  writeFileSync(output, rendered, "utf8");
  return rendered;
}

if (resolve(process.argv[1] ?? "") === resolve(thisFile)) writeMatrixMarkdown();
